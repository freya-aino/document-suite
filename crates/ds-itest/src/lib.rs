//! The integration suite: the deployed system, driven over its public API.
//!
//! Everything else in this workspace tests the suite from the inside.
//! `crates/ds-suite/tests/pipeline.rs` runs the whole pipeline but calls
//! `Pipeline::run` in process; `crates/ds-mcp/tests/live.rs` calls `ds_api::router`
//! in process; the `image` CI job builds the image and never runs the system in it. So
//! until this crate, nothing had exercised the **image**, the **HTTP surface** and a
//! **verified token** together — which is most of what a deployment is.
//!
//! What it talks to is `deploy/compose`; `deploy/compose/README.md` is the entry point.
//! `stack.sh env` prints the variables read here.
//!
//! ## What it can and cannot claim
//!
//! On the `fake` model tier — the one every pull request runs — the answers come from
//! `ds-testkit`, written by us. This suite then proves the system is **wired**: a
//! document is accepted, routed, parsed, stitched, extracted, written to both stores and
//! readable again, with a token the realm signed. It says **nothing** about how well a
//! page is parsed. Fidelity is a `gpu`-tier measurement against a model nobody here
//! wrote, and even there it is reported rather than gated, because the corpus is
//! generated by one generator and its pages are not independent samples.

